# config/weather_constants.py
"""
Справочные константы для анализа погоды и классификации условий радиоприёма.

Ответственность:
  - Наборы кодов METAR (туман, мгла, осадки, грозы) для эвристик.
  - URL-источники METAR (основной и резервный).
  - Списки типов аномалий распространения и типов помех.

Зачем:
  - Централизованное хранение: не дублировать списки в разных функциях.
  - Читаемость: сразу видно, какие явления считаются критичными для УКВ/КВ.
  - Поддержка: если появится новый код METAR или тип помехи — правим в одном месте.
"""

# -----------------------------------------------------------------------------
# METAR token groups — группировка кодов для быстрой эвристики условий
# Зачем: позволяет быстро определять, есть ли туман, мгла, осадки или гроза —
# эти явления напрямую влияют на распространение радиоволн (инверсии, рассеяние,
# поглощение).
# -----------------------------------------------------------------------------
WX_CODES_FOG = {"FG", "MIFG", "BCFG", "PRFG", "FZFG"}
WX_CODES_HAZE = {"HZ", "DU", "SA", "DS", "SS", "BLDU", "BLSA", "BLSS"}
WX_CODES_PRECIP = {"DZ", "RA", "SN", "SG", "IC", "PL", "GR", "GS", "UP"}
WX_CODES_THUNDER = {"TS", "TSRA", "TSSN", "TSPL", "TSGS", "TSGR"}

# -----------------------------------------------------------------------------
# Источники METAR (погода)
# Primary: AWC JSON API — структурированные данные без ключа.
# Backup: NOAA NWS raw TXT — стабильный источник «сырых» METAR-строк.
# Зачем: отказоустойчивость. Если основной API недоступен (сеть, таймаут),
# модуль не ломается, а берёт данные из резервного источника.
# -----------------------------------------------------------------------------
METAR_URL_PRIMARY = "https://aviationweather.gov/api/data/metar?ids={station}&format=json&taf=false&hours=1"
METAR_URL_BACKUP = "https://tgftp.nws.noaa.gov/data/observations/metar/stations/{station}.TXT"

# -----------------------------------------------------------------------------
# ARTIFACT_TYPES — типы аномалий распространения сигнала.
# Стандартизированный список позволяет классифицировать и накапливать статистику
# по условиям дальнего/аномального приёма (тропосферные волноводы, спорадический E,
# EME, метеорное рассеяние и т.п.).
# -----------------------------------------------------------------------------
